-- Conjuntos de tópicos de uma peça, na ordem em que entram no documento.
create table public.topic_kits (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  area_name text not null,
  peca_name text not null,
  name text not null,
  topic_ids bigint[] not null default '{}',
  created_at timestamptz not null default timezone('utc'::text, now()),
  unique (user_id, area_name, peca_name, name)
);

alter table public.topic_kits enable row level security;

create policy "Bloquear acesso para o proprio usuario." on public.topic_kits
  for all to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);
