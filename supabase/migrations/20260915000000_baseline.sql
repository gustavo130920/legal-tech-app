-- Estrutura existente no projeto em 2026-11-03, reconstruída a partir do
-- catálogo do banco. Já estava aplicada quando o versionamento começou.

create table public.user_areas (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references auth.users (id),
  areas text[] not null,
  created_at timestamptz not null default timezone('utc'::text, now())
);

create table public.pecas (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id),
  area_name text not null,
  peca_name text not null,
  created_at timestamptz not null default timezone('utc'::text, now())
);

create table public.topics (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id),
  area_name text not null,
  peca_name text not null,
  title text not null,
  content text not null,
  preview text not null,
  variables text[] not null,
  created_at timestamptz not null default timezone('utc'::text, now())
);

alter table public.user_areas enable row level security;
alter table public.pecas enable row level security;
alter table public.topics enable row level security;

create policy "Bloquear acesso para o proprio usuario." on public.user_areas
  for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Bloquear acesso para o proprio usuario." on public.pecas
  for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Bloquear acesso para o proprio usuario." on public.topics
  for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
